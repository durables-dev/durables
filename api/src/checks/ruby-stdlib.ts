/**
 * Whether a required name is part of Ruby's own library, judged by its first part: `net/http`
 * is, `aws-sdk-s3` is not.
 */
export const isRubyStandardLibrary = (name: string) =>
  rubyStandardLibrary.has(name.split("/")[0] ?? "");
