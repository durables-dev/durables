// Written from the POC-5 API map, boundaries 1 and 3, and extended by the POC-8
// API map, boundary 4 (every SDK, and the Detected panel).

import type { Check } from "./check.js";
import type { Detection, Sdk } from "./detection.js";

export type ReadmeTemplate = {
  markdown: string;
  requiredHeadings: string[];
};

export type SnippetTab = "install" | "activity" | "workflow" | "worker" | "starter";

export type Snippet = {
  tab: SnippetTab;
  /** Absent for install. The file the consumer saves it as. */
  filename?: string;
  /** Monaco language ids. */
  language: "shell" | "python" | "typescript" | "csharp";
  /** Exactly what the copy button copies. */
  content: string;
};

export type Listing = {
  address: string;
  owner: string;
  name: string;
  version: string;
  publishedAt: string;
  publisher: { handle: string; displayName: string; verified: boolean };
  sdk: Sdk;
  code: string;
  /** The stored detection, shown in the Detected panel. */
  detection: Detection;
  /** Five, in order, generated by the template set for `sdk`. */
  snippets: Snippet[];
  configuration: { name: string; purpose: string; line: number }[];
  readme: string;
  checks: Check[];
  /** The highest version: the default. POC-11 API map, boundary 4. */
  latestVersion: string;
  /** Every published version, highest first. */
  versions: { version: string; publishedAt: string }[];
};
